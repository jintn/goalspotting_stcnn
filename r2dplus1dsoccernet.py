# -------------------------
NEG_PER_POS = 5      # negatives per goal (start with 3–10)
MIN_GAP_SEC = 10.0   # negatives must be at least this many seconds away from ANY event time
CLIP_SEC = 4.0       # used to avoid sampling too close to edges
SEED = 42
random.seed(SEED)

# -------------------------
# Split lookup (source of truth)
# -------------------------
SPLITS = {
    "train": set(getListGames("train")),
    "valid": set(getListGames("valid")),
    "test":  set(getListGames("test")),
}
def get_split(rel_game):
    for s, games in SPLITS.items():
        if rel_game in games:
            return s
    return "unknown"

# -------------------------
# Helpers
# -------------------------
def find_jsons(root):
    return glob.glob(os.path.join(root, "**", "*.json"), recursive=True)

def safe_get_event_list(obj):
    if isinstance(obj, dict):
        for k in ["annotations", "Annotations", "Actions", "events", "Labels"]:
            if k in obj and isinstance(obj[k], list):
                return obj[k]
    return []

def event_label(ev):
    for k in ["label", "event", "type", "action", "class"]:
        if k in ev and isinstance(ev[k], str):
            return ev[k]
    if "event" in ev and isinstance(ev["event"], dict) and isinstance(ev["event"].get("label"), str):
        return ev["event"]["label"]
    return None

def parse_game_time(game_time: str):
    # "1 - 12:34"
    if not isinstance(game_time, str) or "-" not in game_time:
        return None, None
    half_str, mmss = game_time.split("-", 1)
    half_str, mmss = half_str.strip(), mmss.strip()
    try:
        half = int(half_str)
        mm, ss = mmss.split(":")
        tsec = int(mm) * 60 + int(ss)
        return half, float(tsec)
    except Exception:
        return None, None

def video_duration_sec(video_path: str):
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        return None
    fps = cap.get(cv2.CAP_PROP_FPS) or 25.0
    n = cap.get(cv2.CAP_PROP_FRAME_COUNT) or 0
    cap.release()
    if n <= 1:
        return None
    return float(n / fps)

def sample_background_times(duration, forbidden_times, n_samples, min_gap=10.0):
    """
    duration: seconds in this half-video
    forbidden_times: list of event times (seconds) in this half
    returns list of sampled background center_sec
    """
    if duration is None or duration <= (CLIP_SEC + 1):
        return []
    lo = CLIP_SEC/2
    hi = duration - CLIP_SEC/2
    if hi <= lo:
        return []

    out = []
    tries = 0
    max_tries = 5000

    forbidden_times = list(forbidden_times)

    while len(out) < n_samples and tries < max_tries:
        tries += 1
        t = random.uniform(lo, hi)
        # far from any event
        if all(abs(t - e) >= min_gap for e in forbidden_times):
            out.append(t)
            forbidden_times.append(t)  # keep negatives spread out too (optional)
    return out

