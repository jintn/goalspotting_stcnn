def extract_clip_cv2(
    video_path,
    center_sec,
    clip_sec=4.0,
    num_frames=16,
    size=112,
):
    cap = cv2.VideoCapture(video_path)
    if not cap.isOpened():
        raise RuntimeError(f"Could not open video: {video_path}")

    fps = cap.get(cv2.CAP_PROP_FPS) or 25.0
    start_sec = max(0.0, center_sec - clip_sec / 2)
    start_frame = int(start_sec * fps)

    frames = []
    step = int(max(1, (clip_sec * fps) / num_frames))

    for i in range(num_frames):
        cap.set(cv2.CAP_PROP_POS_FRAMES, start_frame + i * step)
        ok, frame = cap.read()
        if not ok:
            break
        frame = cv2.resize(frame, (size, size), interpolation=cv2.INTER_AREA)
        frame = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
        frames.append(frame)

    cap.release()

    if len(frames) == 0:
        raise RuntimeError(f"No frames read from: {video_path}")

    # pad if video ended early
    while len(frames) < num_frames:
        frames.append(frames[-1].copy())

    arr = np.stack(frames, axis=0).astype(np.float32) / 255.0  # (T,H,W,C)
    arr = np.transpose(arr, (3, 0, 1, 2))  # (C,T,H,W)
    return torch.from_numpy(arr)

# -------------------------
# Dataset
# -------------------------
class SoccerNetClipDataset(Dataset):
    def __init__(self, df, label2id, clip_sec=4.0, num_frames=16, size=112):
        self.df = df.reset_index(drop=True)
        self.label2id = label2id
        self.clip_sec = clip_sec
        self.num_frames = num_frames
        self.size = size

    def __len__(self):
        return len(self.df)

    def __getitem__(self, idx):
        r = self.df.iloc[idx]
        x = extract_clip_cv2(
            r.video_path,
            r.center_sec,
            self.clip_sec,
            self.num_frames,
            self.size,
        )
        y = self.label2id[r.label]
        return x, torch.tensor(y, dtype=torch.long)

