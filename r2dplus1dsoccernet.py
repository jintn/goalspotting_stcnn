def nms_1d(times, scores, min_separation_sec=8.0):
    """Greedy NMS on 1D timestamps: keep highest score, suppress within +/- min_separation_sec/2."""
    if len(times) == 0:
        return np.array([]), np.array([])
    order = np.argsort(scores)[::-1]
    keep = []
    suppressed = np.zeros(len(times), dtype=bool)
    half = min_separation_sec / 2.0

    for i in order:
        if suppressed[i]:
            continue
        keep.append(i)
        close = np.abs(times - times[i]) <= half
        suppressed |= close
        suppressed[i] = False

    keep = np.array(keep, dtype=int)
    korder = np.argsort(times[keep])
    return times[keep][korder], scores[keep][korder]

def spot_goals_sliding_window(
    video_path,
    clip_sec=4.0,
    stride_sec=1.0,
    num_frames=16,
    size=112,
    threshold=0.998,
    nms_sep_sec=20.0,
    max_seconds=1200,   # set None to scan full 45min; 300 is a fast sanity run
):
    dur, _ = video_duration_fps(video_path)
    end_time = dur if max_seconds is None else min(dur, float(max_seconds))

    t0 = clip_sec / 2.0
    t1 = end_time - clip_sec / 2.0
    if t1 <= t0:
        raise RuntimeError("Video too short for chosen clip_sec/max_seconds.")

    centers = np.arange(t0, t1 + 1e-9, stride_sec, dtype=np.float32)

    probs = []
    with torch.no_grad():
        for c in centers:
            x = extract_clip_cv2(video_path, c, clip_sec=clip_sec, num_frames=num_frames, size=size)
            x = x.unsqueeze(0).to(device)  # [1,C,T,H,W]
            logits = model(x)
            probs.append(torch.softmax(logits, dim=1)[0, goal_id].item())

    probs = np.array(probs, dtype=np.float32)

    det_mask = probs >= threshold
    det_times = centers[det_mask]
    det_scores = probs[det_mask]

    final_times, final_scores = nms_1d(det_times, det_scores, min_separation_sec=nms_sep_sec)
    return centers, probs, final_times, final_scores

